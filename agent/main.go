func swapUsedFrom(m map[string]uint64) uint64 {
	total := m["SwapTotal"]
	free := m["SwapFree"]
	if total <= free {
		return 0
	}
	return total - free
}

func usagePercent(used, total uint64) int {
	if total == 0 {
		return 0
	}
	return int(used * 100 / total)
}

